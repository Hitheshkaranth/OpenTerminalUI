async (page) => {
  const checks = [];
  const errors = [];
  page.on("pageerror", (error) => errors.push(error.message));
  const check = (condition, text) => { if (!condition) throw new Error(text); checks.push(text); };
  await page.setViewportSize({ width: 1440, height: 1100 });
  await page.goto("http://127.0.0.1:5174/equity/getting-started");
  await page.getByRole("heading", { name: "Start with a clear next step." }).waitFor();
  await page.getByRole("button", { name: "Quant research", exact: true }).click();
  check(await page.getByRole("link", { name: "Open Model Lab", exact: true }).getAttribute("href") === "/backtesting/model-lab", "Goal chooser routes to the real Model Lab");
  const manual = page.getByRole("checkbox", { name: /I reviewed a security/ });
  await manual.check();
  await page.reload();
  await page.getByRole("button", { name: "Quant research", exact: true }).waitFor();
  check(await page.getByRole("checkbox", { name: /I reviewed a security/ }).isChecked(), "Manual confirmation persists for the current account");
  check(await page.getByRole("button", { name: "Quant research", exact: true }).getAttribute("aria-pressed") === "true", "Goal selection persists on reload");
  await page.getByRole("button", {name:"Create watchlist",exact:true}).click();
  await page.getByRole("alert").filter({hasText:"Enter a watchlist name."}).waitFor();
  check(true, "Blank watchlist name is rejected before API mutation");
  const listName = "QC adoption " + Date.now();
  await page.getByRole("textbox", { name: "Watchlist name", exact: true }).fill(listName);
  const createdResponse = page.waitForResponse(response => response.request().method() === "POST" && /\/api\/watchlists$/.test(response.url()));
  await page.getByRole("button", { name: "Create watchlist", exact: true }).click();
  const response = await createdResponse;
  check(response.status() === 200, "Personal watchlist creation succeeds through real FastAPI");
  const created = await response.json();
  await page.getByRole("status").filter({hasText:"Created"}).waitFor();
  await page.locator(".getting-started").evaluate(node=>node.scrollIntoView());
  await page.screenshot({path:"output/playwright/wave2-getting-started-desktop.png"});
  await page.setViewportSize({width:390,height:900});
  await page.locator(".getting-started").evaluate(node=>node.scrollIntoView());
  check(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth), "Getting Started has no document overflow at 390px");
  await page.screenshot({path:"output/playwright/wave2-getting-started-mobile.png"});
  await page.setViewportSize({width:1440,height:1100});
  await page.goto("http://127.0.0.1:5174/equity/watchlist?name="+encodeURIComponent(listName));
  await page.getByRole("heading",{name:listName,exact:true}).waitFor();
  const posts=[];
  const track=request=>{if(request.method()==="POST" && /\/api\/watchlists\/[^/]+\/symbols$/.test(request.url())) posts.push(request);};
  page.on("request",track);
  await page.getByRole("button",{name:"Import symbols",exact:true}).click();
  await page.getByRole("textbox",{name:"Symbols or CSV contents",exact:true}).fill("symbol\nNASDAQ:AAPL\nNASDAQ:AAPL\nbad symbol\nNSE:RELIANCE");
  await page.getByRole("button",{name:"Review import",exact:true}).click();
  await page.getByRole("button",{name:"Import reviewed symbols (2)",exact:true}).waitFor();
  check(posts.length===0,"Reviewing CSV does not mutate watchlist");
  const preview=page.getByRole("table",{name:"Symbol import preview for "+listName});
  check((await preview.innerText()).includes("Duplicate")&&(await preview.innerText()).includes("Invalid"),"Preview diagnoses duplicates and invalid rows");
  await page.screenshot({path:"output/playwright/wave2-import-review-desktop.png"});
  await page.getByRole("button",{name:"Import reviewed symbols (2)",exact:true}).click();
  await page.getByRole("status").filter({hasText:"Added 2 symbols"}).waitFor();
  check(posts.length===1,"Confirmation sends exactly one bulk API request");
  const listResponse=await page.request.get("http://127.0.0.1:5174/api/watchlists");
  const persisted=(await listResponse.json()).find(list=>list.id===created.id);
  check(persisted.symbols.length===2&&persisted.symbols.includes("NASDAQ:AAPL")&&persisted.symbols.includes("NSE:RELIANCE"),"Actual saved watchlist contains only reviewed valid symbols");
  await page.getByRole("textbox",{name:"Symbols or CSV contents",exact:true}).fill("NASDAQ:AAPL,NASDAQ:MSFT,###US,NASDAQ:MSFT");
  await page.getByRole("button",{name:"Review import",exact:true}).click();
  await page.getByRole("button",{name:"Import reviewed symbols (1)",exact:true}).waitFor();
  check((await preview.innerText()).includes("Already present"),"TradingView TXT detects existing symbols and skips section metadata");
  await page.setViewportSize({width:390,height:900});
  await preview.scrollIntoViewIfNeeded();
  check(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),"Watchlist import has no document overflow at 390px");
  await page.screenshot({path:"output/playwright/wave2-import-review-mobile.png"});
  await page.setViewportSize({width:1440,height:1100});
  await page.getByRole("button",{name:"Import reviewed symbols (1)",exact:true}).click();
  await page.getByRole("status").filter({hasText:"Added 1 symbol"}).waitFor();
  check(posts.length===2,"Native TXT adds only the new reviewed symbol");
  await page.getByRole("button",{name:"Close symbol import",exact:true}).click();
  await page.getByRole("combobox",{name:"Sort rows",exact:true}).selectOption("symbol");
  await page.reload();
  await page.getByRole("heading",{name:listName,exact:true}).waitFor();
  check(await page.getByRole("combobox",{name:"Sort rows",exact:true}).inputValue()==="symbol","Watchlist sorting persists after reload");
  const first=page.locator("tr[data-watchlist-symbol]").first();
  await first.focus();
  await page.keyboard.press("ArrowDown");
  const focused=await page.evaluate(()=>document.activeElement.getAttribute("data-watchlist-symbol"));
  check(focused==="NASDAQ:MSFT","Keyboard ArrowDown traverses sorted watchlist rows");
  await page.keyboard.press("Enter");
  await page.waitForURL("**/equity/security?ticker=NASDAQ%3AMSFT");
  check(true,"Keyboard Enter opens selected Security Hub with encoded identity");
  page.off("request",track);
  await page.goto("http://127.0.0.1:5174/equity/data-quality");
  await page.getByRole("heading",{name:"Know what your data can support."}).waitFor();
  await page.getByRole("heading",{name:"No monitored symbols yet"}).waitFor();
  check(await page.getByText("Session bars missing",{exact:true}).isVisible(),"Actual monitor empty state remains explicit without fabricated bars");
  await page.screenshot({path:"output/playwright/wave2-data-quality-live.png"});
  await page.setViewportSize({width:390,height:900});
  check(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),"Data Quality has no document overflow at 390px");
  await page.screenshot({path:"output/playwright/wave2-data-quality-mobile.png"});
  await page.setViewportSize({width:1440,height:1100});
  check(errors.length===0,"No uncaught JavaScript errors across actual functional flows");
  return {checks, errors, testWatchlist:{id:created.id,name:listName}, note:"Isolated development database; no live trading orders."};
}
